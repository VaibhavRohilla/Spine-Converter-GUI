// Generate one statically checked kernel per official API generation. No runtime
// duck typing, casts between versions, or fallback method lookup is used.
import { readFile, writeFile, mkdir } from "node:fs/promises";
await mkdir("viewer/src/generated", { recursive: true });
const template = await readFile("viewer/src/kernel.template", "utf8");
const oldConstraints = `return [
 ...skeleton.ikConstraints.map(c=>({name:c.data.name,type:'ik' as const,values:{mix:c.mix,bendDirection:c.bendDirection}})),
 ...skeleton.transformConstraints.map(c=>({name:c.data.name,type:'transform' as const,values:{TRANSFORM_MIX}})),
 ...skeleton.pathConstraints.map(c=>({name:c.data.name,type:'path' as const,values:{position:c.position,spacing:c.spacing}})),PHYSICS_CONSTRAINTS];`;
const newConstraints = `const result:ConstraintPose[]=[];for(const c of skeleton.constraints){
 if(c instanceof spine.IkConstraint)result.push({name:c.data.name,type:'ik',values:{mix:c.appliedPose.mix,bendDirection:c.appliedPose.bendDirection}});
 else if(c instanceof spine.TransformConstraint)result.push({name:c.data.name,type:'transform',values:{mixRotate:c.appliedPose.mixRotate,mixX:c.appliedPose.mixX,mixY:c.appliedPose.mixY}});
 else if(c instanceof spine.PathConstraint)result.push({name:c.data.name,type:'path',values:{position:c.appliedPose.position,spacing:c.appliedPose.spacing}});
 else if(c instanceof spine.PhysicsConstraint)result.push({name:c.data.name,type:'physics',values:{inertia:c.appliedPose.inertia,strength:c.appliedPose.strength,damping:c.appliedPose.damping,mix:c.appliedPose.mix}});
 }return result;`;
for (const family of ["38", "40", "41", "42", "43"]) {
  const legacy = family === "38",
    v43 = family === "43";
  const values = {
    IMPORT: legacy
      ? "import {spine} from '../../.runtime/spine-webgl';"
      : "import * as spine from 'spine" + family + "';",
    WEBGL: legacy ? "spine.webgl" : "spine",
    ATLAS: legacy
      ? "atlas=new spine.TextureAtlas(atlasText,texture);"
      : "atlas=new spine.TextureAtlas(atlasText);for(const page of atlas.pages)page.setTexture(texture(page.name));",
    WORLD: ["42", "43"].includes(family)
      ? "skeleton.updateWorldTransform(spine.Physics.update);"
      : "skeleton.updateWorldTransform();",
    SETUP: v43 ? "skeleton.setupPose();" : "skeleton.setToSetupPose();",
    LOCAL: v43 ? "b.pose" : "b",
    WORLDPOSE: v43 ? "b.appliedPose" : "b",
    WORLDPOSE_FOR_VALIDATE: v43 ? "b.appliedPose" : "b",
    SLOTPOSE: v43 ? "s.appliedPose" : "s",
    ATTACHMENT: v43 ? "p.attachment" : "s.getAttachment()",
    DRAWORDER: v43 ? "skeleton.drawOrder.appliedPose" : "skeleton.drawOrder",
    SETSKIN: v43 ? "skeleton.setSkin(skin);" : "skeleton.setSkinByName(skin);",
    TICK: family === "41" ? "" : "skeleton.update(delta);",
    PREMULTIPLY: v43 ? "!page.pma" : "false",
    ALPHA_CHECK: v43
      ? "void alphaModes;"
      : "if(alphaModes.size!==1)throw new ViewerError('UNSUPPORTED_RENDER_FEATURE','Mixed page alpha modes require 4.3.');",
    TEXTURE: v43
      ? "new WEBGL.GLTexture(context,image,page.pma)"
      : "new WEBGL.GLTexture(context,image)",
    DRAW: v43
      ? "renderer.drawSkeleton(skeleton);if(Object.values(debug).some(Boolean))renderer.drawSkeletonDebug(skeleton);"
      : "renderer.drawSkeleton(skeleton,pma);if(Object.values(debug).some(Boolean))renderer.drawSkeletonDebug(skeleton,pma);",
    REGION_VERTICES: v43
      ? "a.computeWorldVertices(s,a.getOffsets(p),worldVertices,0,2);"
      : ["41", "42"].includes(family)
        ? "a.computeWorldVertices(s,worldVertices,0,2);"
        : "a.computeWorldVertices(s.bone,worldVertices,0,2);",
    VERTEX_VERTICES: v43
      ? "a.computeWorldVertices(skeleton,s,0,a.worldVerticesLength,worldVertices,0,2);"
      : "a.computeWorldVertices(s,0,a.worldVerticesLength,worldVertices,0,2);",
    CONSTRAINTS: v43 ? newConstraints : oldConstraints,
    TRANSFORM_MIX: legacy
      ? "rotateMix:c.rotateMix,translateMix:c.translateMix,scaleMix:c.scaleMix,shearMix:c.shearMix"
      : "mixRotate:c.mixRotate,mixX:c.mixX,mixY:c.mixY",
    PHYSICS_CONSTRAINTS:
      family === "42"
        ? "...skeleton.physicsConstraints.map(c=>({name:c.data.name,type:'physics' as const,values:{inertia:c.inertia,strength:c.strength,damping:c.damping,mix:c.mix}}))"
        : "",
  };
  let source = template;
  for (let i = 0; i < 3; i++)
    source = source.replace(/\b[A-Z_]{3,}\b/g, (key) => values[key] ?? key);
  await writeFile(
    `viewer/src/generated/kernel${family}.ts`,
    "// Generated by viewer/scripts/generate.mjs from kernel.template.\n" +
      source,
  );
}

const manifest = JSON.parse(
  await readFile("src/fnx_spine_forge/viewer/runtime_manifest.json", "utf8"),
);
const revisions = Object.fromEntries(
  manifest.runtimes
    .filter((r) => r.embeddedImplemented)
    .map((r) => [r.family, r.revision]),
);
await writeFile(
  "viewer/src/generated/revisions.ts",
  "export const revisions = " +
    JSON.stringify(revisions, null, 2) +
    " as const;\n",
);
